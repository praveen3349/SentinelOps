const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

function run(command, args, options = {}) {
  return new Promise((resolve) => {
    const child = spawn(command, args, { windowsHide: true, ...options });
    let stdout = ''; let stderr = '';
    child.stdout?.on('data', (data) => { stdout += data.toString(); });
    child.stderr?.on('data', (data) => { stderr += data.toString(); });
    child.on('error', (error) => resolve({ ok: false, error: error.message, stdout, stderr }));
    child.on('close', (code) => resolve({ ok: code === 0, code, stdout, stderr }));
  });
}

async function getDockerStatus() {
  const version = await run('docker', ['version', '--format', '{{.Client.Version}}']);
  if (!version.ok) return { installed: false, running: false, message: 'Docker Desktop is not installed or its CLI is not available.' };
  const engine = await run('docker', ['info', '--format', '{{.ServerVersion}}']);
  if (!engine.ok) return { installed: true, running: false, clientVersion: version.stdout.trim(), message: 'Docker is installed. Start Docker Desktop to run containers.' };
  return { installed: true, running: true, clientVersion: version.stdout.trim(), engineVersion: engine.stdout.trim(), message: 'Docker Engine is ready.' };
}

function sanitizeName(value) {
  return String(value || 'app').toLowerCase().replace(/[^a-z0-9_.-]+/g, '-').replace(/^-+|-+$/g, '') || 'app';
}

function dockerSpec(service) {
  const kind = service.type || '';
  const command = service.runCommand || '';
  const port = Number(service.port) || null;
  if (/Python/i.test(kind)) return { baseImage: 'python:3.12-slim', port, dockerfile: `FROM python:3.12-slim\nWORKDIR /app\nENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1\nCOPY . .\nRUN if [ -f requirements.txt ]; then pip install --no-cache-dir -r requirements.txt; elif [ -f pyproject.toml ]; then pip install --no-cache-dir .; fi\n${port ? `EXPOSE ${port}\n` : ''}CMD ["sh", "-c", ${JSON.stringify(command || 'python main.py')}]\n` };
  if (/Go/i.test(kind)) return { baseImage: 'golang:1.22-alpine', port, dockerfile: `FROM golang:1.22-alpine\nWORKDIR /app\nCOPY . .\nRUN go mod download\n${port ? `EXPOSE ${port}\n` : ''}CMD ["sh", "-c", ${JSON.stringify(command || 'go run .')}]\n` };
  if (/Rust/i.test(kind)) return { baseImage: 'rust:1.78-slim', port, dockerfile: `FROM rust:1.78-slim\nWORKDIR /app\nCOPY . .\n${port ? `EXPOSE ${port}\n` : ''}CMD ["sh", "-c", ${JSON.stringify(command || 'cargo run')}]\n` };
  const packageManager = service.packageManager || 'npm';
  const install = packageManager === 'pnpm' ? 'corepack enable && if [ -f pnpm-lock.yaml ]; then pnpm install --frozen-lockfile; else pnpm install; fi' : packageManager === 'yarn' ? 'corepack enable && if [ -f yarn.lock ]; then yarn install --frozen-lockfile; else yarn install; fi' : 'if [ -f package-lock.json ]; then npm ci; else npm install; fi';
  return { baseImage: 'node:20-alpine', port, dockerfile: `FROM node:20-alpine\nWORKDIR /app\nCOPY . .\nRUN ${install}\n${port ? `EXPOSE ${port}\n` : ''}CMD ["sh", "-c", ${JSON.stringify(command || 'npm start')}]\n` };
}

function assertInside(root, target) {
  const resolvedRoot = path.resolve(root);
  const resolvedTarget = path.resolve(target);
  if (resolvedTarget !== resolvedRoot && !resolvedTarget.startsWith(`${resolvedRoot}${path.sep}`)) throw new Error('Unsafe Docker asset path.');
  return resolvedTarget;
}

function generateDockerAssets(project, services) {
  const generated = [];
  const compose = { name: `sentinelops-${sanitizeName(project.name)}`, services: {} };
  for (const service of services) {
    const directory = assertInside(project.path, path.join(project.path, service.directory || '.'));
    const configDirectory = assertInside(project.path, path.join(directory, '.sentinelops'));
    fs.mkdirSync(configDirectory, { recursive: true });
    const spec = dockerSpec(service);
    const dockerfilePath = path.join(configDirectory, 'Dockerfile');
    fs.writeFileSync(dockerfilePath, spec.dockerfile, 'utf8');
    const serviceName = sanitizeName(service.id || service.name);
    const relativeDirectory = path.relative(project.path, directory) || '.';
    compose.services[serviceName] = {
      build: { context: relativeDirectory.replace(/\\/g, '/'), dockerfile: '.sentinelops/Dockerfile' },
      image: `${sanitizeName(project.name)}-${serviceName}:local`,
      ...(spec.port ? { ports: [`${spec.port}:${spec.port}`] } : {})
    };
    generated.push({ id: service.id, serviceName, baseImage: spec.baseImage, dockerfilePath, image: `${sanitizeName(project.name)}-${serviceName}:local`, port: spec.port });
  }
  const composePath = assertInside(project.path, path.join(project.path, '.sentinelops-compose.yml'));
  const yaml = `# Generated by SentinelOps. Regenerate after changing your selected tech stack.\nname: ${compose.name}\nservices:\n${Object.entries(compose.services).map(([name, service]) => `  ${name}:\n    build:\n      context: ${service.build.context}\n      dockerfile: ${service.build.dockerfile}\n    image: ${service.image}\n${service.ports ? `    ports:\n${service.ports.map((port) => `      - "${port}"`).join('\n')}\n` : ''}`).join('')}`;
  fs.writeFileSync(composePath, yaml, 'utf8');
  return { generated, composePath };
}

module.exports = { getDockerStatus, dockerSpec, generateDockerAssets, sanitizeName };
